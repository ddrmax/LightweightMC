# Era ordering used for the eraFor() lookup
ERAS = ["LEGACY", "MODERN", "LATEST"]


def load_seed(name):
    path = os.path.join(SEED_DIR, name)
    with open(path, "r") as f:
        return json.load(f)


def build_version_table():
    """Returns entries sorted by protocol: list of (proto, (version, era))."""
    data = load_seed("versions.json")
    rows = []
    for v in data["versions"]:
        proto = int(v["protocol"])
        version = str(v["version"])
        era = v["era"].upper()
        if era not in ERAS:
            raise ValueError(f"Unknown era '{era}' for {version} in versions.json")
        rows.append((proto, version, era))

    seen = {}
    for proto, version, era in rows:
        if proto not in seen:
            seen[proto] = (version, era)
    entries = sorted(seen.items())
    return entries


def build_packet_id_table():
    """Merges the 1.8 baseline with any per-era override files into a single map."""
    base = load_seed("packet_ids_1.8.json")
    result = {}
    for era in ERAS:
        result[era] = {"s2c": dict(base["s2c"]), "c2s": dict(base["c2s"])}

    for era in ERAS:
        fname = f"packet_ids_{era.lower()}.json"
        path = os.path.join(SEED_DIR, fname)
        if os.path.exists(path):
            with open(path, "r") as f:
                override = json.load(f)
            result[era]["s2c"].update(override.get("s2c", {}))
            result[era]["c2s"].update(override.get("c2s", {}))

    for era, tables in result.items():
        for direction in ("s2c", "c2s"):
            for kind in tables[direction]:
                if kind not in PACKET_KINDS:
                    raise ValueError(f"Unknown PacketKind '{kind}' in {era}/{direction} table")

    return result


def emit_protocol_versions(out_dir, entries):
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "// AUTO-GENERATED by tools/gen_protocol_data.py -- DO NOT EDIT.",
        "// Regenerate: python3 tools/gen_protocol_data.py",
        f"// Generated: {ts}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <cstddef>",
        "#include <cstdlib>",
        "",
        "namespace LightweightMC::Network::Protocol",
        "{",
        "",
        "    enum class Era : std::uint8_t",
        "    {",
    ]
    for i, era in enumerate(ERAS):
        lines.append(f"        {era} = {i},")
    lines.extend([
        f"        COUNT = {len(ERAS)}",
        "    };",
        "",
        "    inline const char *eraName(Era era)",
        "    {",
        "        switch (era)",
        "        {",
    ])
    for era in ERAS:
        lines.append(f'            case Era::{era}: return "{era}";')
    lines.extend([
        '            default: return "UNKNOWN";',
        "        }",
        "    }",
        "",
        "    struct ProtocolVersionInfo",
        "    {",
        "        int32_t protocol;",
        "        const char *version;",
        "        Era era;",
        "    };",
        "",
        "    static constexpr ProtocolVersionInfo kProtocolVersions[] = {",
    ])
    for proto, (version, era) in entries:
        lines.append(f'        {{ {proto}, "{version}", Era::{era} }},')
    lines.extend([
        "    };",
        "",
        "    static constexpr std::size_t kProtocolVersionCount = sizeof(kProtocolVersions) / sizeof(kProtocolVersions[0]);",
        "",
        "    inline const ProtocolVersionInfo *resolve(int32_t protocol)",
        "    {",
        "        for (std::size_t i = 0; i < kProtocolVersionCount; ++i)",
        "        {",
        "            if (kProtocolVersions[i].protocol == protocol)",
        "                return &kProtocolVersions[i];",
        "        }",
        "        return nullptr;",
        "    }",
        "",
        "    inline const ProtocolVersionInfo *nearestSupported(int32_t protocol)",
        "    {",
        "        if (kProtocolVersionCount == 0) return nullptr;",
        "        int32_t best = kProtocolVersions[0].protocol;",
        "        for (std::size_t i = 0; i < kProtocolVersionCount; ++i)",
        "        {",
        "            if (std::abs(kProtocolVersions[i].protocol - protocol) < std::abs(best - protocol))",
        "                best = kProtocolVersions[i].protocol;",
        "        }",
        "        return resolve(best);",
        "    }",
        "",
        "    inline Era eraFor(int32_t protocol)",
        "    {",
        "        const ProtocolVersionInfo *info = resolve(protocol);",
        "        if (!info) info = nearestSupported(protocol);",
        "        return info ? info->era : Era::LEGACY;",
        "    }",
        "",
        "} // namespace LightweightMC::Network::Protocol",
        ""
    ])

    path = os.path.join(out_dir, "protocol_versions.h")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def emit_packet_ids(out_dir, id_table):
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    kind_index = {k: i for i, k in enumerate(PACKET_KINDS)}

    lines = [
        "// AUTO-GENERATED by tools/gen_protocol_data.py -- DO NOT EDIT.",
        "// Regenerate: python3 tools/gen_protocol_data.py",
        f"// Generated: {ts}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <cstddef>",
        '#include "network/protocol/PacketKind.hpp"',
        '#include "protocol/data/protocol_versions.h"',
        "",
        "namespace LightweightMC::Network::Protocol",
        "{",
        ""
    ]

    for direction in ("s2c", "c2s"):
        label = "S2C" if direction == "s2c" else "C2S"
        lines.append(f"    // {label} packet IDs per era, indexed by PacketKind. -1 = not supported in that era.")
        for era in ERAS:
            table = id_table[era][direction]
            arr = [-1] * len(PACKET_KINDS)
            for kind, pid in table.items():
                arr[kind_index[kind]] = int(pid)
            lines.append(f"    static constexpr std::int32_t k{label}_{era}[] = {{")
            for i in range(0, len(arr), 8):
                chunk = arr[i:i + 8]
                names = ", ".join(f"/* {PACKET_KINDS[i + j]} */ {v}" for j, v in enumerate(chunk))
                lines.append(f"        {names},")
            lines.append("    };")
            lines.append("")

    max_18_id = max((pid for pid in id_table["LEGACY"]["s2c"].values() if pid >= 0), default=0)
    lines.append("    // S2C reverse lookup per era, indexed by 1.8 wire ID. -1 = unmapped.")
    for era in ERAS:
        table = id_table[era]["s2c"]
        arr = [-1] * (max_18_id + 1)
        for kind, pid in table.items():
            legacy_pid = id_table["LEGACY"]["s2c"].get(kind, -1)
            if 0 <= legacy_pid <= max_18_id:
                arr[legacy_pid] = int(pid)
        lines.append(f"    static constexpr std::int32_t kS2CReverse_{era}[] = {{")
        for i in range(0, len(arr), 8):
            chunk = arr[i:i + 8]
            names = ", ".join(f"/* {i + j:02X} */ {v}" for j, v in enumerate(chunk))
            lines.append(f"        {names},")
        lines.append("    };")
        lines.append("")

    lines.append("    // Reverse lookup: C2S id -> PacketKind (-1 = unknown/ignored).")
    for era in ERAS:
        table = id_table[era]["c2s"]
        max_id = max(table.values(), default=0)
        rev = [-1] * (max_id + 1)
        for kind, pid in table.items():
            rev[int(pid)] = kind_index[kind]
        lines.append(f"    static constexpr std::int32_t kC2S_{era}_Reverse[] = {{")
        for i in range(0, len(rev), 16):
            chunk = rev[i:i + 16]
            comma = "," if i + 16 < len(rev) else ""
            lines.append("        " + ", ".join(str(v) for v in chunk) + comma)
        lines.append("    };")
        lines.append("")

    lines.extend([
        "    inline std::int32_t s2cPacketId(Era era, PacketKind kind)",
        "    {",
        "        const std::size_t idx = static_cast<std::size_t>(kind);",
        "        switch (era)",
        "        {",
    ])
    for era in ERAS:
        lines.append(f"            case Era::{era}: return kS2C_{era}[idx];")
    lines.extend([
        "            default: return -1;",
        "        }",
        "    }",
        "",
        "    inline std::int32_t s2cWireIdFromLegacy(Era era, std::int32_t legacyWireId)",
        "    {",
        "        if (legacyWireId < 0) return -1;",
        "        switch (era)",
        "        {",
    ])
    for era in ERAS:
        lines.append(f"            case Era::{era}: {{")
        lines.append(f"                if (legacyWireId >= static_cast<std::int32_t>(sizeof(kS2CReverse_{era}) / sizeof(kS2CReverse_{era}[0]))) return -1;")
        lines.append(f"                return kS2CReverse_{era}[legacyWireId];")
        lines.append("            }")
    lines.extend([
        "            default: return -1;",
        "        }",
        "    }",
        "",
        "    inline PacketKind c2sPacketKind(Era era, std::int32_t id)",
        "    {",
        "        switch (era)",
        "        {",
    ])
    for era in ERAS:
        lines.append(f"            case Era::{era}: {{")
        lines.append(f"                if (id < 0 || id >= static_cast<std::int32_t>(sizeof(kC2S_{era}_Reverse) / sizeof(kC2S_{era}_Reverse[0]))) return PacketKind::UNKNOWN;")
        lines.append(f"                const std::int32_t k = kC2S_{era}_Reverse[id];")
        lines.append("                return k < 0 ? PacketKind::UNKNOWN : static_cast<PacketKind>(k);")
        lines.append("            }")
    lines.extend([
        "            default: return PacketKind::UNKNOWN;",
        "        }",
        "    }",
        "",
        "} // namespace LightweightMC::Network::Protocol",
        ""
    ])

    path = os.path.join(out_dir, "packet_ids.h")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def emit_packet_id_handler(out_dir):
    """Generates the PacketIdHandler class header."""
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "// AUTO-GENERATED by tools/gen_protocol_data.py -- DO NOT EDIT.",
        "// Regenerate: python3 tools/gen_protocol_data.py",
        f"// Generated: {ts}",
        "#pragma once",
        "",
        "#include <cstdint>",
        '#include "network/protocol/PacketKind.hpp"',
        '#include "protocol/data/protocol_versions.h"',
        '#include "protocol/data/packet_ids.h"',
        "",
        "namespace LightweightMC::Network::Protocol",
        "{",
        "    /**",
        "     * @brief High-level Handler class to query Packet IDs based on protocol version or Era.",
        "     */",
        "    class PacketIdHandler",
        "    {",
        "    public:",
        "        // --- Lookups by Era ---",
        "",
        "        /**",
        "         * @brief Get Server-to-Client packet ID for a given Era and PacketKind.",
        "         * @return Wire packet ID or -1 if unsupported.",
        "         */",
        "        static inline std::int32_t getS2CPacketId(Era era, PacketKind kind)",
        "        {",
        "            return s2cPacketId(era, kind);",
        "        }",
        "",
        "        /**",
        "         * @brief Get Client-to-Server PacketKind from a raw wire packet ID for a given Era.",
        "         * @return PacketKind or PacketKind::UNKNOWN if invalid/unsupported.",
        "         */",
        "        static inline PacketKind getC2SPacketKind(Era era, std::int32_t rawId)",
        "        {",
        "            return c2sPacketKind(era, rawId);",
        "        }",
        "",
        "        // --- Lookups by Protocol Version ---",
        "",
        "        /**",
        "         * @brief Get Server-to-Client packet ID for a raw protocol version.",
        "         */",
        "        static inline std::int32_t getS2CPacketId(std::int32_t protocolVersion, PacketKind kind)",
        "        {",
        "            return s2cPacketId(eraFor(protocolVersion), kind);",
        "        }",
        "",
        "        /**",
        "         * @brief Get Client-to-Server PacketKind from raw ID and protocol version.",
        "         */",
        "        static inline PacketKind getC2SPacketKind(std::int32_t protocolVersion, std::int32_t rawId)",
        "        {",
        "            return c2sPacketKind(eraFor(protocolVersion), rawId);",
        "        }",
        "",
        "        /**",
        "         * @brief Translate a 1.8 S2C wire ID to an equivalent wire ID in the target Era.",
        "         */",
        "        static inline std::int32_t translateS2CLegacyWireId(Era targetEra, std::int32_t legacyWireId)",
        "        {",
        "            return s2cWireIdFromLegacy(targetEra, legacyWireId);",
        "        }",
        "",
        "        /**",
        "         * @brief Translate a 1.8 S2C wire ID to an equivalent wire ID in the target protocol version.",
        "         */",
        "        static inline std::int32_t translateS2CLegacyWireId(std::int32_t targetProtocol, std::int32_t legacyWireId)",
        "        {",
        "            return s2cWireIdFromLegacy(eraFor(targetProtocol), legacyWireId);",
        "        }",
        "    };",
        "",
        "} // namespace LightweightMC::Network::Protocol",
        ""
    ]

    path = os.path.join(out_dir, "PacketIdHandler.hpp")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return path


def main():
    parser = argparse.ArgumentParser(description="LightweightMC protocol data generator")
    parser.add_argument("--out", default=os.path.join("..", "include", "protocol", "data"), help="Output directory for generated headers")
    args = parser.parse_args()

    out_dir = args.out
    os.makedirs(out_dir, exist_ok=True)

    entries = build_version_table()
    id_table = build_packet_id_table()

    p1 = emit_protocol_versions(out_dir, entries)
    p2 = emit_packet_ids(out_dir, id_table)
    p3 = emit_packet_id_handler(out_dir)

    print(f"[gen_protocol_data] Wrote {p1}")
    print(f"[gen_protocol_data] Wrote {p2}")
    print(f"[gen_protocol_data] Wrote {p3}")
    print(f"[gen_protocol_data] {len(entries)} protocol versions, {len(ERAS)} eras processed.")


if __name__ == "__main__":
    main()